// Um PostgreSQL de verdade, descartável, com a loja fictícia (Fase 42b, ADR-006). Nunca um banco do dono.
// Tem um usuário só de leitura (rastro_leitura, com CONNECT, USAGE e SELECT), como o README recomenda,
// e uma função IMMUTABLE que mente (grava numa tabela): o planejador a executa ao simplificar a consulta,
// e o banco recusa a gravação.
public sealed class PostgreSqlContainerFixture : IAsyncLifetime
{
    public const string Image = "postgres:17-alpine";
    public const string ReaderPassword = "LeituraDeTeste#123";
    private PostgreSqlContainer? _container;

    // O dono do banco (para preparar e conferir) e o usuário só de leitura (o que o Rastro usaria).
    public string AdminConnectionString { get; private set; } = string.Empty;
    public string ReaderConnectionString { get; private set; } = string.Empty;

    public async Task InitializeAsync()
    {
        if (new DockerFactAttribute().Skip is not null) return;
        _container = new PostgreSqlBuilder(Image).WithDatabase("loja").Build();
        await _container.StartAsync();
        AdminConnectionString = _container.GetConnectionString();
        await RunAsync(AdminConnectionString, $"""
            CREATE EXTENSION IF NOT EXISTS pgcrypto;
            CREATE TABLE clientes (
                id integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_clientes PRIMARY KEY,
                nome character varying(120) NOT NULL,
                email character varying(200) NOT NULL,
                cpf char(11),
                preferencias jsonb,
                criado_em timestamp with time zone NOT NULL);
            CREATE UNIQUE INDEX ux_clientes_email ON clientes (email);
            CREATE TABLE pedidos (
                id serial CONSTRAINT pk_pedidos PRIMARY KEY,
                cliente_id integer NOT NULL CONSTRAINT fk_pedidos_clientes_cliente_id REFERENCES clientes (id) ON DELETE RESTRICT,
                status character varying(30) NOT NULL,
                total numeric(10,2) NOT NULL,
                criado_em timestamp with time zone NOT NULL);
            CREATE INDEX ix_pedidos_cliente_id ON pedidos (cliente_id) INCLUDE (total);
            CREATE VIEW vw_abertos AS SELECT id, total FROM pedidos WHERE status = 'aberto';
            CREATE TABLE marcas (quando timestamp with time zone);
            CREATE FUNCTION marca_mentirosa() RETURNS integer LANGUAGE plpgsql IMMUTABLE AS $$
            BEGIN INSERT INTO marcas VALUES (now()); RETURN 1; END $$;
            CREATE FUNCTION pedidos_do_cliente(p_cliente integer, OUT quantos bigint) LANGUAGE sql AS
            'SELECT count(*) FROM pedidos WHERE cliente_id = p_cliente';
            INSERT INTO clientes (nome, email, criado_em) VALUES ('Ana (teste)', 'ana@teste.test', now());
            INSERT INTO pedidos (cliente_id, status, total, criado_em) VALUES (1, 'aberto', 10, now());
            CREATE ROLE rastro_leitura LOGIN PASSWORD '{ReaderPassword}';
            GRANT CONNECT ON DATABASE loja TO rastro_leitura;
            GRANT USAGE ON SCHEMA public TO rastro_leitura;
            GRANT SELECT ON ALL TABLES IN SCHEMA public TO rastro_leitura;
            """);
        ReaderConnectionString = new NpgsqlConnectionStringBuilder(AdminConnectionString) { Username = "rastro_leitura", Password = ReaderPassword }.ConnectionString;
    }

    public async Task DisposeAsync()
    {
        if (_container is not null) await _container.DisposeAsync();
    }

    public static async Task RunAsync(string connectionString, string sql)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync();
    }

    public static async Task<long> CountAsync(string connectionString, string table)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand($"SELECT count(*) FROM {table}", connection);
        return (long)(await command.ExecuteScalarAsync())!;
    }
}

// Cenários INF-PGL-NNN com PostgreSQL de verdade: catálogo e plano estimado pelo EXPLAIN sem ANALYZE,
// sem executar a consulta, e as camadas que impedem a gravação.
public class PostgreSqlLiveDatabaseTests(PostgreSqlContainerFixture server) : IClassFixture<PostgreSqlContainerFixture>
{
    private readonly NpgsqlLiveDatabase _live = new();

    [DockerFact] // INF-PGL-010
    public async Task Catalogo_TabelasColunasChavesIndicesViewEFuncaoComoOCatalogoEscreve()
    {
        var fragment = await _live.ReadCatalogAsync(server.ReaderConnectionString, default);

        Assert.Equal(["clientes", "marcas", "pedidos"], fragment.Tables.Select(t => t.Name).Order());
        var pedidos = fragment.Tables.Single(t => t.Name == "pedidos");
        Assert.Equal(["id", "cliente_id", "status", "total", "criado_em"], pedidos.Columns.Select(c => c.Name));
        Assert.Equal(["integer", "integer", "character varying(30)", "numeric(10,2)", "timestamp with time zone"], pedidos.Columns.Select(c => c.Type));
        Assert.True(pedidos.Columns[0].Identity);
        Assert.True(fragment.Tables.Single(t => t.Name == "clientes").Columns[0].Identity);
        Assert.Equal(("pk_pedidos", "id"), (pedidos.PrimaryKey!.Name, pedidos.PrimaryKey.Columns.Single()));
        var fk = Assert.Single(pedidos.ForeignKeys);
        Assert.Equal(("clientes", "cliente_id", DeleteAction.Restrict), (fk.PrincipalTable, fk.Columns[0], fk.OnDelete));
        var index = Assert.Single(pedidos.Indexes);
        Assert.Equal(("ix_pedidos_cliente_id", "cliente_id", "total"), (index.Name, index.Columns.Single(), index.Included.Single()));
        Assert.True(fragment.Tables.Single(t => t.Name == "clientes").Columns.Single(c => c.Name == "cpf").Nullable);
        Assert.Equal("jsonb", fragment.Tables.Single(t => t.Name == "clientes").Columns.Single(c => c.Name == "preferencias").Type);
        Assert.Equal(["id", "total"], Assert.Single(fragment.Views).Columns);
        // As funções da extensão (pgcrypto) ficam de fora; as do usuário entram, com o parâmetro de saída.
        Assert.Equal(["marca_mentirosa", "pedidos_do_cliente"], fragment.Procedures.Select(p => p.Name).Order());
        var count = fragment.Procedures.Single(p => p.Name == "pedidos_do_cliente");
        Assert.Equal([("p_cliente", "integer", false), ("quantos", "bigint", true)], count.Parameters.Select(p => (p.Name, p.Type, p.Output)));
        Assert.Equal(3, await _live.CountTablesAsync(server.ReaderConnectionString, default));
    }

    [DockerFact] // INF-PGL-011
    public async Task Plano_DaConsultaDoPrototipoComParametros_VarreduraSemExecutar()
    {
        const string sql = """
            SELECT * FROM pedidos p
            JOIN clientes c ON c.id = p.cliente_id
            WHERE p.criado_em::date >= $1 AND c.email ILIKE '%@gmail.com' AND p.status = @status
            ORDER BY p.criado_em DESC
            """;
        var guard = PgSqlPlanGuard.Check(sql);
        Assert.True(guard.Allowed, guard.Reason);

        var plan = ExplainPlanReader.Read(await _live.EstimatedPlanAsync(server.ReaderConnectionString, sql, guard.Variables, default));

        Assert.True(plan.TotalCost > 0);
        // O ILIKE com o curinga no começo lê clientes inteira (Seq Scan), como o achado sem IA avisa.
        Assert.Contains(plan.Operations, o => o.Scan && o.Object == "clientes");
        Assert.InRange(plan.Operations.Sum(o => o.Percent), 99, 101);
        Assert.Empty(plan.MissingIndexes);
    }

    [DockerFact] // INF-PGL-012
    public async Task Plano_DeDeleteUpdateEInsert_NaoMudaNada()
    {
        var before = (await PostgreSqlContainerFixture.CountAsync(server.AdminConnectionString, "pedidos"),
            await PostgreSqlContainerFixture.CountAsync(server.AdminConnectionString, "pedidos WHERE status = 'aberto'"));

        foreach (var sql in new[] { "DELETE FROM pedidos", "UPDATE pedidos SET status = 'mudado'", "INSERT INTO pedidos (cliente_id, status, total, criado_em) SELECT cliente_id, status, total, criado_em FROM pedidos" })
        {
            var plan = ExplainPlanReader.Read(await _live.EstimatedPlanAsync(server.AdminConnectionString, sql, [], default));
            Assert.NotEmpty(plan.Operations);
        }

        Assert.Equal((1L, 1L), before);
        Assert.Equal(before, (await PostgreSqlContainerFixture.CountAsync(server.AdminConnectionString, "pedidos"),
            await PostgreSqlContainerFixture.CountAsync(server.AdminConnectionString, "pedidos WHERE status = 'aberto'")));
    }

    [DockerFact] // INF-PGL-013
    public async Task SegundaCamada_DuasInstrucoesEFuncaoQueGrava_ORecusaDoBancoSemGravarNada()
    {
        // Se a porta deixasse passar duas instruções, o comando de um só lote as recusa.
        var two = await Assert.ThrowsAsync<PostgresException>(() => _live.EstimatedPlanAsync(server.AdminConnectionString, "SELECT 1; DELETE FROM pedidos", [], default));
        Assert.Equal("42601", two.SqlState);

        // A função IMMUTABLE que grava roda no planejamento, e o próprio PostgreSQL recusa a gravação nela
        // (0A000); a conexão só de leitura (25006) é mais uma camada atrás dessa.
        var write = await Assert.ThrowsAsync<PostgresException>(() => _live.EstimatedPlanAsync(server.AdminConnectionString, "SELECT id FROM pedidos WHERE id = marca_mentirosa()", [], default));
        Assert.Contains(write.SqlState, new[] { "0A000", "25006" });

        Assert.Equal(1, await PostgreSqlContainerFixture.CountAsync(server.AdminConnectionString, "pedidos"));
        Assert.Equal(0, await PostgreSqlContainerFixture.CountAsync(server.AdminConnectionString, "marcas"));
    }

    [DockerFact] // INF-PGL-014
    public async Task UsuarioSoDeLeitura_PlanoDoSelectSaiEODoDeleteRecusadoPorPermissao()
    {
        Assert.NotEmpty(ExplainPlanReader.Read(await _live.EstimatedPlanAsync(server.ReaderConnectionString, "SELECT id FROM pedidos WHERE id = 1", [], default)).Operations);

        var denied = await Assert.ThrowsAsync<PostgresException>(() => _live.EstimatedPlanAsync(server.ReaderConnectionString, "DELETE FROM pedidos WHERE id = 1", [], default));
        Assert.Equal("42501", denied.SqlState);
    }
}
