SET statement_timeout = 0;
SELECT pg_catalog.set_config('search_path', '', false);

CREATE TABLE public.cupons (
    id integer NOT NULL,
    codigo character varying(20) NOT NULL,
    desconto numeric(5,2)
);

ALTER TABLE public.cupons ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.cupons_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

COPY public.cupons (id, codigo, desconto) FROM stdin;
1	D'AVILA10	10.00
2	BEMVINDO	5.00
\.

ALTER TABLE ONLY public.cupons
    ADD CONSTRAINT cupons_pkey PRIMARY KEY (id);

CREATE UNIQUE INDEX ux_cupons_codigo ON public.cupons USING btree (codigo);
